#!/usr/bin/env bash
# Install DejaGnu, Expect and Tcl under tools/ without root.
#
# The C testsuite needs runtest, which the host does not provide and which
# cannot be installed system-wide here (no root, no sudo). The Debian packages
# are unpacked into tools/root and exported through tools/dejagnu.env, which
# make check-c sources. Nothing is added to the repository; tools/ is ignored.
#
# Usage: scripts/bootstrap-dejagnu.sh [--force]
#   --force   unpack the packages again even if runtest is already present
set -euo pipefail

cd "$(dirname "$0")/.."

prefix=${DEJAGNU_PREFIX:-tools/root}
cache=${DEJAGNU_CACHE:-tools/debs}
env_file=tools/dejagnu.env
packages=(tcl8.6 libtcl8.6 tcl tcl-expect expect dejagnu)
force=0
[ "${1:-}" = --force ] && force=1

have_runtest() {
  [ -x "$prefix/usr/bin/runtest" ] && [ -x "$prefix/usr/bin/expect" ] && [ -x "$prefix/usr/bin/tclsh8.6" ]
}

die() { echo "bootstrap-dejagnu: $*" >&2; exit 1; }

if [ "$force" = 1 ] || ! have_runtest; then
  command -v apt-get >/dev/null || die "apt-get not found; install dejagnu and expect yourself"
  command -v dpkg >/dev/null || die "dpkg not found"
  mkdir -p "$cache" "$prefix"
  echo "bootstrap-dejagnu: downloading ${packages[*]}"
  ( cd "$cache" && apt-get download "${packages[@]}" ) || die "apt-get download failed (network?)"
  for deb in "$cache"/*.deb; do
    [ -f "$deb" ] || continue
    dpkg -x "$deb" "$prefix"
  done
fi

# The tcl package ships a tclsh symlink into /etc/alternatives, which does not
# exist inside the private prefix. Point it at the interpreter we just unpacked.
if [ ! -x "$prefix/usr/bin/tclsh" ]; then
  ln -sf tclsh8.6 "$prefix/usr/bin/tclsh"
fi

root_abs=$(cd "$prefix" && pwd)
libdir=""
for candidate in "$root_abs"/usr/lib/*-linux-gnu; do
  if [ -e "$candidate/libtcl8.6.so" ]; then libdir=$candidate; break; fi
done
[ -n "$libdir" ] || die "libtcl8.6.so not found under $root_abs/usr/lib"

{
  echo '# Generated by scripts/bootstrap-dejagnu.sh; source this file, do not commit it.'
  printf 'export PATH="%s/usr/bin:$PATH"\n' "$root_abs"
  printf 'export DEJAGNULIBS="%s/usr/share/dejagnu"\n' "$root_abs"
  printf 'export TCL_LIBRARY="%s/usr/share/tcltk/tcl8.6"\n' "$root_abs"
  printf 'export LD_LIBRARY_PATH="%s${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"\n' "$libdir"
} > "$env_file"

# shellcheck disable=SC1090
. "$env_file"

command -v runtest >/dev/null || die 'runtest is not on PATH after bootstrap'
echo "bootstrap-dejagnu: $(runtest --version | head -n 1)"
echo "bootstrap-dejagnu: $(expect -v | head -n 1)"
echo "bootstrap-dejagnu: wrote $env_file (sourced by make check-c)"